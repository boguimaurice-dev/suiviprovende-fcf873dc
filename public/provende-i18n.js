  let lang = "fr";
  try {
    lang = localStorage.getItem(LANG_KEY) || "fr";
  } catch {
    lang = "fr";
  }
  if (!DICT[lang]) lang = "fr";

  const norm = (s) => s.replace(/\s+/g, " ").trim();

  function lookup(text) {
    const dict = DICT[lang];
    if (!dict) return null;
    const key = norm(text);
    if (!key) return null;
    const hit = dict[key];
    if (!hit) return null;
    // conserve les espaces autour du texte d'origine
    const lead = text.match(/^\s*/)[0];
    const tail = text.match(/\s*$/)[0];
    return lead + hit + tail;
  }

  function translateNode(node) {
    if (node.nodeType === 3) {
      if (node.__frOriginal === undefined) node.__frOriginal = node.nodeValue;
      const source = node.__frOriginal;
      const out = lang === "fr" ? source : lookup(source);
      const next = out == null ? source : out;
      if (node.nodeValue !== next) node.nodeValue = next;
      return;
    }
    if (node.nodeType !== 1) return;
    const tag = node.tagName;
    if (tag === "SCRIPT" || tag === "STYLE" || node.dataset?.noI18n === "1") return;

    for (const attr of ["placeholder", "title", "aria-label"]) {
      if (node.hasAttribute && node.hasAttribute(attr)) {
        const store = "__frAttr_" + attr;
        if (node[store] === undefined) node[store] = node.getAttribute(attr);
        const source = node[store];
        const out = lang === "fr" ? source : lookup(source);
        node.setAttribute(attr, out == null ? source : out);
      }
    }
    if (tag === "OPTION") {
      // le texte de l'option est un nœud texte, la valeur reste intacte
    }
    for (const child of Array.from(node.childNodes)) translateNode(child);
  }

  let scheduled = false;
  function translateAll() {
    if (scheduled) return;
    scheduled = true;
    requestAnimationFrame(() => {
      scheduled = false;
      observer.disconnect();
      try {
        translateNode(document.body);
      } finally {
        observe();
      }
    });
  }

  const observer = new MutationObserver(translateAll);
  function observe() {
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }

  function mountSelector() {
    const side = document.querySelector(".side");
    if (!side || document.getElementById("langSelect")) return;
    const wrap = document.createElement("div");
    wrap.style.cssText = "margin-top:8px";
    wrap.dataset.noI18n = "1";
    const select = document.createElement("select");
    select.id = "langSelect";
    select.setAttribute("aria-label", "Langue / Language");
    select.style.cssText =
      "width:100%;padding:8px 10px;border-radius:10px;border:1px solid rgba(255,255,255,.25);background:transparent;color:inherit;font:inherit";
    for (const l of LANGS) {
      const opt = document.createElement("option");
      opt.value = l.code;
      opt.textContent = l.label;
      opt.style.color = "#111";
      if (l.code === lang) opt.selected = true;
      select.appendChild(opt);
    }
    select.addEventListener("change", () => {
      lang = DICT[select.value] || select.value === "fr" ? select.value : "fr";
      try {
        localStorage.setItem(LANG_KEY, lang);
      } catch {
        /* stockage indisponible */
      }
      translateAll();
      document.documentElement.setAttribute("lang", lang);
    });
    wrap.appendChild(select);
    const foot = side.querySelector(".side-foot");
    if (foot) side.insertBefore(wrap, foot);
    else side.appendChild(wrap);
  }

